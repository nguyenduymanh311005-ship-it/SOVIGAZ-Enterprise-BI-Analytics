WITH TONG_TIEN_DON_HANG AS (
    SELECT 
        ORDER_ID, 
        SUM(QUANTITY * UNIT_PRICE) AS TONG_TIEN
    FROM ORDER_ITEMS
    GROUP BY ORDER_ID
)
SELECT 
    ORDER_ID, 
    TONG_TIEN
FROM TONG_TIEN_DON_HANG
